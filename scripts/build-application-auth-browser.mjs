import { build } from 'esbuild';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
const output = 'src/modules/website-builder/browser/generated/application-auth-script.ts';
const result = await build({ entryPoints: ['src/modules/website-builder/browser/application-auth-screen.ts'], bundle: true, write: false, platform: 'browser', format: 'iife', target: 'es2020', minify: true, legalComments: 'none' });
const contents = '// Generated by scripts/build-application-auth-browser.mjs. Do not edit.\nexport const applicationAuthScript = ' + JSON.stringify(result.outputFiles[0].text) + ';\n';
if (process.argv.includes('--check')) {
  if (await readFile(output, 'utf8') !== contents) throw new Error('Application auth browser bundle is stale.');
  console.log('PASS application Auth browser bundle matches source');
} else {
  await mkdir('src/modules/website-builder/browser/generated', { recursive: true });
  await writeFile(output, contents);
  console.log('Prepared isolated application Auth browser bundle; not deployed');
}
