import './build-application-page-browser.mjs';
import './build-application-auth-browser.mjs';
import { build } from 'esbuild';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
const output = 'server/generated/website-application-runtime.js';
const result = await build({ entryPoints: ['server/website-application-runtime.ts'], bundle: true, write: false, platform: 'node', format: 'esm', target: 'node22', external: ['@supabase/supabase-js'],
  banner: { js: '// Generated by scripts/build-application-runtime.mjs; edit the original server/service modules.' },
});
const contents = result.outputFiles[0].text;
if (process.argv.includes('--check')) {
  if (await readFile(output, 'utf8') !== contents) throw new Error('Private application runtime bundle is stale.');
  console.log('PASS private application runtime matches tested source');
} else {
  await mkdir('server/generated', { recursive: true });
  await writeFile(output, contents);
  console.log(`Prepared ${output}; feature flag remains disabled`);
}
