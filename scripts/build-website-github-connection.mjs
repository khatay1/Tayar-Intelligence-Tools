import { build } from 'esbuild';
import { mkdir, readFile, writeFile } from 'node:fs/promises';

const output = 'supabase/functions/website-github-connection/index.ts';
const environmentKeys = ['SUPABASE_URL', 'SUPABASE_SERVICE_ROLE_KEY', 'WEBSITE_GITHUB_APP_CLIENT_ID',
  'WEBSITE_GITHUB_APP_CLIENT_SECRET', 'WEBSITE_GITHUB_CALLBACK_URL', 'WEBSITE_GITHUB_RETURN_URL'];
const environment = `{${environmentKeys.map(key => `${JSON.stringify(key)}:Deno.env.get(${JSON.stringify(key)})`).join(',')}}`;
const result = await build({ entryPoints: ['server/website-github-connection-edge.ts'], bundle: true, write: false,
  platform: 'neutral', format: 'esm', target: 'es2022',
  banner: { js: '// Generated by scripts/build-website-github-connection.mjs; edit server/service source.\n/* eslint-disable no-var, @typescript-eslint/no-unused-vars -- Generated bundle. */' },
  footer: { js: `Deno.serve(createWebsiteGitHubConnectionDeployment({environment:${environment}}));` },
  plugins: [{ name: 'pinned-supabase-edge', setup(builder) {
    builder.onResolve({ filter: /^@supabase\/supabase-js$/ }, () => ({ path: 'npm:@supabase/supabase-js@2.57.4', external: true }));
  } }],
});
const contents = result.outputFiles[0].text;
if (process.argv.includes('--check')) {
  if (await readFile(output, 'utf8') !== contents) throw new Error('GitHub connection Edge bundle is stale.');
  console.log('PASS GitHub connection Edge bundle matches source');
} else {
  await mkdir('supabase/functions/website-github-connection', { recursive: true });
  await writeFile(output, contents);
  console.log(`Prepared ${output}; not deployed`);
}
