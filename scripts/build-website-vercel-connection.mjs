import { build } from 'esbuild';
import { mkdir, readFile, writeFile } from 'node:fs/promises';

const output = 'supabase/functions/website-vercel-connection/index.ts';
const environmentKeys = ['SUPABASE_URL', 'SUPABASE_SERVICE_ROLE_KEY',
  'WEBSITE_VERCEL_INTEGRATION_SLUG', 'WEBSITE_VERCEL_CLIENT_ID', 'WEBSITE_VERCEL_CLIENT_SECRET',
  'WEBSITE_VERCEL_CALLBACK_URL', 'WEBSITE_VERCEL_RETURN_URL', 'TAYAR_PLATFORM_VERCEL_ACCOUNT_ID',
  'TAYAR_GITHUB_APP_CLIENT_ID', 'TAYAR_GITHUB_APP_PRIVATE_KEY_PKCS8'];
const environment = `{${environmentKeys.map(key => `${JSON.stringify(key)}:Deno.env.get(${JSON.stringify(key)})`).join(',')}}`;
const result = await build({ entryPoints: ['server/website-vercel-connection-edge.ts'], bundle: true, write: false,
  platform: 'neutral', format: 'esm', target: 'es2022',
  banner: { js: '// Generated by scripts/build-website-vercel-connection.mjs; edit server/service source.\n/* eslint-disable no-var, @typescript-eslint/no-unused-vars -- Generated bundle. */' },
  footer: { js: `Deno.serve(createWebsiteVercelConnectionEdge({environment:${environment}}));` },
  plugins: [{ name: 'pinned-supabase-edge', setup(builder) {
    builder.onResolve({ filter: /^@supabase\/supabase-js$/ },
      () => ({ path: 'npm:@supabase/supabase-js@2.57.4', external: true }));
  } }],
});
const contents = result.outputFiles[0].text;
if (process.argv.includes('--check')) {
  if (await readFile(output, 'utf8') !== contents) throw new Error('Vercel connection Edge bundle is stale.');
  console.log('PASS Vercel connection Edge bundle matches trusted source');
} else {
  await mkdir('supabase/functions/website-vercel-connection', { recursive: true });
  await writeFile(output, contents);
  console.log(`Prepared ${output}; not deployed`);
}
