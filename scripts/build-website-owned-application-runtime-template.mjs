import { build } from 'esbuild';
import { mkdir, readFile, writeFile } from 'node:fs/promises';

const output = 'server/generated/website-owned-application-runtime-template.ts';
const result = await build({
  entryPoints: ['server/website-owned-application-runtime-template.ts'],
  tsconfig: 'tsconfig.app.json',
  bundle: true,
  write: false,
  platform: 'node',
  format: 'cjs',
  target: 'node22',
  footer: { js: 'module.exports = module.exports.default;' },
});
const runtime = result.outputFiles[0].text;
const contents = `// Generated by scripts/build-website-owned-application-runtime-template.mjs; edit server/service source.\nexport const websiteOwnedApplicationRuntimeTemplate = ${JSON.stringify(runtime)};\n`;

if (process.argv.includes('--check')) {
  if (await readFile(output, 'utf8') !== contents) throw new Error('Owned application runtime template is stale.');
  console.log('PASS owned application runtime template matches trusted route source');
} else {
  await mkdir('server/generated', { recursive: true });
  await writeFile(output, contents);
  console.log(`Prepared ${output}; not deployed`);
}
