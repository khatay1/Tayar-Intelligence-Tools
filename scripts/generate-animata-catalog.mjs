import fs from 'node:fs';
import path from 'node:path';

const [, , sourceRootArg, outputArg] = process.argv;
if (!sourceRootArg || !outputArg) {
  console.error('Usage: node scripts/generate-animata-catalog.mjs <animata-source-root> <output-file>');
  process.exit(1);
}

const REVISION = 'de9aabb0eed14e0db944bb07720961ddc450c672';
const sourceRoot = path.resolve(sourceRootArg);
const registryRoot = path.join(sourceRoot, 'public', 'r');
const outputFile = path.resolve(outputArg);

function walk(dir, result = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full, result);
    else if (entry.isFile() && entry.name.endsWith('.json')) result.push(full);
  }
  return result;
}

function toPosix(value) {
  return value.split(path.sep).join('/');
}

function resolveSourcePath(installPath) {
  const clean = String(installPath || '').replace(/^\.\//, '');
  const candidates = [
    clean,
    clean.startsWith('components/components/') ? clean.slice('components/'.length) : null,
    clean.startsWith('components/animata/') ? clean.slice('components/'.length) : null,
    clean.startsWith('components/hooks/') ? clean.slice('components/'.length) : null,
    clean.startsWith('components/lib/') ? clean.slice('components/'.length) : null,
  ].filter(Boolean);

  for (const candidate of candidates) {
    if (fs.existsSync(path.join(sourceRoot, candidate))) return candidate;
  }
  throw new Error(`Unable to map Animata registry file back to pinned source: ${installPath}`);
}

function normalizeRegistryDependency(value) {
  const dep = String(value || '').trim();
  if (!dep) return '';
  try {
    const url = new URL(dep);
    if (url.hostname === 'animata.design' || url.hostname === 'www.animata.design') {
      const parts = url.pathname.split('/').filter(Boolean);
      const rIndex = parts.indexOf('r');
      if (rIndex >= 0 && parts.length >= rIndex + 3) {
        const category = parts[rIndex + 1];
        const name = parts[rIndex + 2].replace(/\.json$/i, '');
        return `${category}-${name}`;
      }
    }
  } catch {
    // Non-URL registry dependency (for example a shadcn primitive).
  }
  return dep;
}

const files = walk(registryRoot).sort();
const items = files.map((file) => {
  const raw = JSON.parse(fs.readFileSync(file, 'utf8'));
  const sourceFiles = Array.isArray(raw.files)
    ? raw.files.map((entry) => ({ path: toPosix(resolveSourcePath(entry.path)) }))
    : [];

  if (!raw.name || !sourceFiles.length) {
    throw new Error(`Invalid generated Animata registry item: ${file}`);
  }

  return {
    name: raw.name,
    title: raw.title || raw.name,
    description: raw.description || `${raw.title || raw.name} from Animata`,
    type: raw.type || 'registry:component',
    dependencies: Array.isArray(raw.dependencies) ? raw.dependencies : [],
    registryDependencies: Array.isArray(raw.registryDependencies)
      ? raw.registryDependencies.map(normalizeRegistryDependency).filter(Boolean)
      : [],
    files: sourceFiles,
    ...(raw.css ? { css: raw.css } : {}),
    ...(raw.cssVars ? { cssVars: raw.cssVars } : {}),
  };
});

const content = `// AUTO-GENERATED. DO NOT EDIT MANUALLY.
// Source: codse/animata @ ${REVISION}
// Generated by Animata's own registry builder, then normalized for Tayar.
export const ANIMATA_CATALOG_REVISION = '${REVISION}';
export const ANIMATA_CATALOG_COUNT = ${items.length};
export const ANIMATA_CATALOG = ${JSON.stringify(items, null, 2)} as const;
`;

fs.mkdirSync(path.dirname(outputFile), { recursive: true });
fs.writeFileSync(outputFile, content);
console.log(`Generated ${items.length} pinned Animata registry items -> ${outputFile}`);
