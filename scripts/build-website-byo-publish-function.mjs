import { build } from 'esbuild';
import { mkdir, readFile, writeFile } from 'node:fs/promises';

const output = 'supabase/functions/website-byo-publish/index.ts';
const environment = `{
  "TAYAR_PLATFORM_SUPABASE_URL": Deno.env.get("SUPABASE_URL"),
  "TAYAR_PLATFORM_SUPABASE_SECRET_KEY": Deno.env.get("SUPABASE_SERVICE_ROLE_KEY"),
  "TAYAR_PLATFORM_ORIGIN": Deno.env.get("TAYAR_PLATFORM_ORIGIN"),
  "TAYAR_PLATFORM_SUPABASE_ORGANIZATION_ID": Deno.env.get("TAYAR_PLATFORM_SUPABASE_ORGANIZATION_ID"),
  "TAYAR_PLATFORM_VERCEL_ACCOUNT_ID": Deno.env.get("TAYAR_PLATFORM_VERCEL_ACCOUNT_ID"),
  "TAYAR_GITHUB_APP_CLIENT_ID": Deno.env.get("TAYAR_GITHUB_APP_CLIENT_ID"),
  "TAYAR_GITHUB_APP_PRIVATE_KEY_PKCS8": Deno.env.get("TAYAR_GITHUB_APP_PRIVATE_KEY_PKCS8")
}`;

const result = await build({
  entryPoints: ['server/website-byo-publish-deployment-entry.ts'],
  bundle: true,
  write: false,
  platform: 'neutral',
  format: 'esm',
  target: 'es2022',
  banner: {
    js: '// Generated by scripts/build-website-byo-publish-function.mjs; edit server source.\n/* eslint-disable no-var, @typescript-eslint/no-unused-vars -- Generated bundle. */',
  },
  footer: {
    js: `Deno.serve(createWebsiteByoPublishDeploymentEntry({ environment: ${environment} }));`,
  },
  plugins: [{
    name: 'pinned-supabase-edge',
    setup(builder) {
      builder.onResolve(
        { filter: /^@supabase\/supabase-js$/ },
        () => ({ path: 'npm:@supabase/supabase-js@2.57.4', external: true }),
      );
    },
  }],
});

const contents = result.outputFiles[0].text;
if (process.argv.includes('--check')) {
  if (await readFile(output, 'utf8') !== contents) {
    throw new Error('BYO publish Supabase Edge bundle is stale.');
  }
  console.log('PASS BYO publish Supabase Edge bundle matches trusted deployment entry');
} else {
  await mkdir('supabase/functions/website-byo-publish', { recursive: true });
  await writeFile(output, contents);
  console.log(`Prepared ${output}; not deployed`);
}
