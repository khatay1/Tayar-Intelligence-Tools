import assert from 'node:assert/strict';
import { mkdtemp, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { build } from 'esbuild';

// Exercise the generated transport shared by the Edge deployment, with no DB
// or provider connection. Malformed bodies must never start a publish worker.
const dir = await mkdtemp(join(tmpdir(), 'tayar-publish-body-'));
try {
  const output = join(dir, 'endpoint.cjs');
  const compiled = await build({ entryPoints: ['server/generated/website-byo-publish-endpoint.js'],
    bundle: true, platform: 'node', format: 'cjs', write: false });
  await writeFile(output, compiled.outputFiles[0].text);
  const { handleWebsiteByoPublish: handle } = (await import(pathToFileURL(output))).default;
  const ownerId = '11111111-1111-4111-8111-111111111111';
  const projectId = '22222222-2222-4222-8222-222222222222';
  const operationId = '33333333-3333-4333-8333-333333333333';
  const body = JSON.stringify({ action: 'preview', projectId, operationId });
  let workers = 0, lookups = 0;
  const context = {
    platform: {
      auth: { getUser: async () => ({ data: { user: { id: ownerId } }, error: null }) },
      from: () => {
        lookups++;
        const query = { select: () => query, eq: () => query, is: () => query,
          maybeSingle: async () => ({ data: { id: projectId }, error: null }) };
        return query;
      },
    },
    runPreview: async () => {
      workers++;
      return { status: 'pending', checkpoint: { ownerId, projectId, operationId,
        environment: 'preview', stage: 'observing', version: 1, liveUrl: null } };
    },
    readStatus: async () => { throw Error('Unexpected status read'); },
  };
  const request = (value, headers = {}) => new Request('https://edge.example', {
    method: 'POST', duplex: 'half', body: value,
    headers: { 'content-type': 'application/json', authorization: 'Bearer a.b.c', ...headers },
  });
  assert.equal((await handle(request(body.padEnd(2048)), context)).status, 202);
  assert.equal(workers, 1, 'Exactly 2048 ASCII bytes remain supported');
  const reject = async (value, headers) => {
    const before = { workers, lookups };
    const response = await handle(request(value, headers), context);
    assert.equal(response.status, 400);
    assert.deepEqual(await response.json(), { error: 'Invalid publish request.' });
    assert.deepEqual({ workers, lookups }, before, 'Body rejection precedes project lookup and publish work');
  };
  await reject(body.padEnd(2049));
  await reject(body, { 'content-length': '2049' });
  for (const length of ['-1', 'NaN', '1e3', '1.5']) await reject(body, { 'content-length': length });
  await reject(body, { 'content-encoding': 'gzip' });
  // Duplicate early value is ignored by JSON.parse; bytes still count toward
  // the transport limit even when JavaScript string length is below the cap.
  const unicode = '{"action":"' + 'é'.repeat(1000) + '",' + body.slice(1);
  assert.ok(unicode.length < 2048 && new TextEncoder().encode(unicode).length > 2048);
  await reject(unicode);
  const prefix = new TextEncoder().encode('{"action":"');
  const suffix = new TextEncoder().encode('",' + body.slice(1));
  await reject(new Uint8Array([...prefix, 0xff, ...suffix]));

  let pulls = 0, cancelled = false;
  const oversized = new ReadableStream({
    pull(controller) {
      pulls++;
      controller.enqueue(new Uint8Array(2049));
    },
    cancel() { cancelled = true; },
  }, { highWaterMark: 0 });
  await reject(oversized, { 'content-length': '1' });
  assert.equal(pulls, 1, 'Stop on first oversized chunk despite a false declared size');
  assert.equal(cancelled, true, 'Cancel an unfinished oversized stream');

  const encoded = new TextEncoder().encode(body);
  let index = 0;
  const chunked = new ReadableStream({
    pull(controller) {
      if (index === encoded.length) controller.close();
      else controller.enqueue(encoded.slice(index, ++index));
    },
  });
  assert.equal((await handle(request(chunked), context)).status, 202);
  assert.equal(workers, 2, 'Legitimate chunked requests work without Content-Length');

  let stalledCancelled = false;
  const stalled = new ReadableStream({
    start(controller) { controller.enqueue(new TextEncoder().encode(body)); },
    cancel() { stalledCancelled = true; return new Promise(() => {}); },
  });
  const start = Date.now();
  await reject(stalled);
  assert.ok(Date.now() - start < 8000, 'Incomplete stream has a finite total deadline');
  assert.equal(stalledCancelled, true, 'Timeout cancels input without awaiting an unresponsive source');
  console.log('PASS generated BYO transport: bounded bytes/chunks/deadline, cancellation, UTF-8, headers, zero rejected-request publish work');
} finally {
  await rm(dir, { recursive: true, force: true });
}
