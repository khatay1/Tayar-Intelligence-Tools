import { build } from 'esbuild';
import { mkdir, readFile, writeFile } from 'node:fs/promises';

const output = 'supabase/functions/website-application-backend-link/index.ts';
const result = await build({
  entryPoints: ['server/website-application-backend-link.ts'],
  bundle: true, write: false, platform: 'neutral', format: 'esm', target: 'es2022',
  banner: { js: '// Generated by scripts/build-application-backend-link.mjs; edit the server/service source.\n/* eslint-disable no-var, @typescript-eslint/no-unused-vars -- Generated bundler syntax; lint the original server/service modules. */' },
  plugins: [{ name: 'pinned-supabase-edge', setup(builder) {
    builder.onResolve({ filter: /^(?:npm:)?@supabase\/supabase-js(?:@.*)?$/ }, () => ({ path: 'npm:@supabase/supabase-js@2.57.4', external: true }));
  } }],
});
const contents = result.outputFiles[0].text;
if (process.argv.includes('--check')) {
  if (await readFile(output, 'utf8') !== contents) throw new Error('Application backend Edge bundle is stale; run build:application-backend-link.');
  console.log('PASS application backend Edge bundle matches tested source');
} else {
  await mkdir('supabase/functions/website-application-backend-link', { recursive: true });
  await writeFile(output, contents);
  console.log(`Prepared ${output}; not deployed`);
}
