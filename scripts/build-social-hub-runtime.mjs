import { build } from 'esbuild';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
const output = 'server/generated/social-hub-deployment.js';
const result = await build({ entryPoints: ['server/social-hub-deployment.ts'], bundle: true, write: false,
  platform: 'node', format: 'esm', target: 'node22', external: ['@supabase/supabase-js'],
  banner: { js: '// Generated by scripts/build-social-hub-runtime.mjs; edit server source.\n/* eslint-disable */' } });
const contents = result.outputFiles[0].text;
if (process.argv.includes('--check')) {
  if (await readFile(output, 'utf8') !== contents) throw Error('Social Hub runtime bundle is stale.');
  console.log('PASS Social Hub runtime bundle matches source');
} else {
  await mkdir('server/generated', { recursive: true }); await writeFile(output, contents);
  console.log(`Prepared ${output}; feature activation remains off`);
}
