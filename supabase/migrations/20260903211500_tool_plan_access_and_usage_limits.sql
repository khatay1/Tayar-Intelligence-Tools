create or replace function public.tool_access_state(p_tool_id text)
returns jsonb language plpgsql stable security definer set search_path=public as $$
declare v_uid uuid:=auth.uid(); v_id text:=trim(coalesce(p_tool_id,'')); v_req text:='free'; v_enabled boolean:=true; v_plan text:='free'; v_allowed boolean:=false;
begin
 if v_uid is null then raise exception 'Authentication required'; end if;
 if v_id='' then raise exception 'Tool id is required'; end if;
 select r.minimum_plan,r.enabled into v_req,v_enabled from public.tool_access_rules r where r.tool_id=v_id;
 v_req:=coalesce(v_req,'free'); v_enabled:=coalesce(v_enabled,true); v_plan:=public.team_effective_plan(v_uid);
 v_allowed:=v_enabled and (v_req='free' or (v_req='pro' and v_plan in ('pro','business')) or (v_req='business' and v_plan='business'));
 return jsonb_build_object('tool_id',v_id,'enabled',v_enabled,'required_plan',v_req,'effective_plan',v_plan,'allowed',v_allowed);
end; $$;
revoke all on function public.tool_access_state(text) from public,anon;
grant execute on function public.tool_access_state(text) to authenticated,service_role;

create or replace function public.check_tool_usage(p_tool_id text)
returns jsonb language plpgsql stable security definer set search_path=public as $$
declare v_uid uuid:=auth.uid(); v_id text:=trim(coalesce(p_tool_id,'')); v_access jsonb; v_plan text; v_limit integer; v_period text; v_start timestamptz; v_used bigint:=0; v_ai boolean:=false;
begin
 if v_uid is null then raise exception 'Authentication required'; end if;
 if v_id='' then raise exception 'Tool id is required'; end if;
 v_access:=public.tool_access_state(v_id);
 if coalesce((v_access->>'allowed')::boolean,false)=false then return v_access||jsonb_build_object('usage_allowed',false,'reason','plan_or_tool_access'); end if;
 v_plan:=coalesce(v_access->>'effective_plan','free');
 select l.period,case v_plan when 'business' then l.business_limit when 'pro' then l.pro_limit else l.free_limit end into v_period,v_limit from public.tool_plan_limits l where l.tool_id=v_id;
 if not found or v_limit is null then return v_access||jsonb_build_object('usage_allowed',true,'limit',null,'used',null,'remaining',null,'period',coalesce(v_period,'monthly')); end if;
 if v_period='daily' then v_start:=date_trunc('day',now()); elsif v_period='monthly' then v_start:=date_trunc('month',now()); else v_start:=to_timestamp(0); end if;
 v_ai:=v_id in ('cv-builder','cover-letter','ai-writer','document-ai','study-assistant','translator','ai-chat','website-builder','code-assistant','image-tools');
 if v_ai then select count(*) into v_used from public.ai_usage u where u.user_id=v_uid and u.tool=v_id and u.status='success' and u.created_at>=v_start;
 else select count(*) into v_used from public.tool_usage_events e where e.user_id=v_uid and e.tool_id=v_id and e.created_at>=v_start; end if;
 return v_access||jsonb_build_object('usage_allowed',v_used<v_limit,'limit',v_limit,'used',v_used,'remaining',greatest(v_limit-v_used,0),'period',v_period,'reason',case when v_used>=v_limit then 'quota_exhausted' else null end);
end; $$;
revoke all on function public.check_tool_usage(text) from public,anon;
grant execute on function public.check_tool_usage(text) to authenticated,service_role;
