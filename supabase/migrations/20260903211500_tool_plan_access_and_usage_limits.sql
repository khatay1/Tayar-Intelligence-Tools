create table if not exists public.tool_access_rules (
  tool_id text primary key,
  minimum_plan text not null default 'free' check (minimum_plan in ('free','pro','business')),
  enabled boolean not null default true,
  updated_at timestamptz not null default now(),
  updated_by uuid references auth.users(id)
);
alter table public.tool_access_rules enable row level security;

drop policy if exists tool_access_rules_select on public.tool_access_rules;
create policy tool_access_rules_select on public.tool_access_rules for select to authenticated using (true);
drop policy if exists tool_access_rules_admin_insert on public.tool_access_rules;
create policy tool_access_rules_admin_insert on public.tool_access_rules for insert to authenticated with check ((select public.is_admin()));
drop policy if exists tool_access_rules_admin_update on public.tool_access_rules;
create policy tool_access_rules_admin_update on public.tool_access_rules for update to authenticated using ((select public.is_admin())) with check ((select public.is_admin()));

grant select on public.tool_access_rules to authenticated;
grant insert, update on public.tool_access_rules to authenticated;
grant all on public.tool_access_rules to service_role;

